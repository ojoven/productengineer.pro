// Writes the reference for figures as Markdown, from the catalogue. `npm run figures:docs` saves it
// under docs/; a test fails when the saved files and the catalogue disagree.
//
//   docs/figures.md            how to add a figure, the rules, the picker and the index
//   docs/figures/<group>.md    every figure of a group: when to use it, its props, its MDX
import { loadAtlas } from '../../atlas/load.ts';
import { nodeCodes } from '../../atlas/render.ts';
import { COLOURS, EVIDENCE_KINDS, FIGURES, FRAME_PROPS, GROUPS, PICKER, toMdx, type FigureDoc, type PropDoc } from './catalog.ts';

const NOTE = '<!-- Generated by `npm run figures:docs` from src/components/figures/catalog.ts. Edit the catalogue, then run it again. -->';

const groupFile = (group: string) => `figures/${group}.md`;
const anchor = (name: string) => name.toLowerCase();
const link = (f: FigureDoc, fromRoot = true) => `[\`${f.name}\`](${fromRoot ? groupFile(f.group) : `${f.group}.md`}#${anchor(f.name)})`;
const byName = new Map(FIGURES.map((f) => [f.name, f]));

function prop(p: PropDoc): string {
  return `- **\`${p.name}\`**${p.required ? ' *(required)*' : ''} \`${p.type}\`: ${p.note}`;
}

function figure(f: FigureDoc): string {
  const out: string[] = [];
  out.push(`## ${f.name}`, '', `\`${f.code}\` · ${f.what}`, '');
  out.push('**Use it for**', '', ...f.use.map((u) => `- ${u}`), '');
  if (f.avoid) out.push(`**Not for:** ${f.avoid}`, '');
  const atlas = [`territories ${f.territories.join(', ')}`, f.skills.length ? `skills ${f.skills.map((s) => `\`${s}\``).join(', ')}` : ''].filter(Boolean);
  out.push(`**Skills Map:** ${atlas.join('; ')}`, '');
  out.push(`**Motion:** ${f.motion.length ? f.motion.join(', ') : 'none'}`, '');
  out.push('**Props**', '', ...f.props.map(prop));
  out.push('', f.frameless ? 'It has no frame, so it takes none of the frame props.' : 'Plus the frame props: `title`, `caption`, `evidence`, `source`.', '');
  f.examples.forEach((ex, i) => {
    out.push(ex.label ? `**Example: ${ex.label}**` : i === 0 ? '**Example**' : '**Another example**', '', '```mdx', toMdx(f.name, ex.props), '```', '');
  });
  return out.join('\n');
}

function groupDoc(groupId: string): string {
  const g = GROUPS.find((x) => x.id === groupId)!;
  const figures = FIGURES.filter((f) => f.group === g.id);
  return [
    `# Figures: ${g.name}`,
    '',
    NOTE,
    '',
    `${g.question} ${g.intro}`,
    '',
    `How to add one to an entry, and the rules they all follow: [figures.md](../figures.md).`,
    '',
    `In this file: ${figures.map((f) => `[${f.name}](#${anchor(f.name)})`).join(' · ')}`,
    '',
    figures.map(figure).join('\n'),
  ].join('\n');
}

function mainDoc(): string {
  const out: string[] = [];
  out.push('# Figures', '', NOTE, '');
  out.push(
    `Figures are the visual vocabulary of In practice entries: ${FIGURES.length} components for screens, flows, numbers,`,
    'decisions and links to the Skills Map. An entry written as `.mdx` uses them by name. All of them, live,',
    'with their examples: `/figures/` (in development, <http://localhost:4321/figures/>).',
    '',
    'A figure proves one point. Its `caption` is that point as a sentence. When the reader could take',
    'its content for something it is not, its `evidence` says how it is known.',
    '',
  );

  out.push('## Add a figure to an entry', '');
  out.push(
    '1. **Write the sentence the figure must prove.** It becomes the `caption`. When the prose already',
    '   makes the point, the section needs no figure.',
    '2. **Pick the figure.** Find the kind of entry and the section in',
    '   [Which figure for which section](#which-figure-for-which-section), or scan the [index](#index).',
    '   Then read its *Use it for* and *Not for* in the group file.',
    '3. **Make the entry MDX.** Rename `src/content/fieldwork/<id>.md` to `<id>.mdx`. The URL stays the',
    '   same and figures need no import.',
    '4. **Copy the example from the group file and replace all of its data** with the data of the entry.',
    '   Leave a blank line before and after the figure.',
    '5. **Say how it is known, only where it matters.** Set `evidence` and `source` when the figure',
    '   carries numbers or claims a reader could take as checked when they are not, or that differ from',
    '   how the rest of the entry is known ([Evidence](#evidence)). Leave them out otherwise.',
    '6. **Add the screenshots** as WebP under `public/img/fieldwork/<id>/`, 560 px wide for a phone and',
    '   1280 px for a desktop, and point `src` at `/img/fieldwork/<id>/<name>.webp`. While a screenshot',
    '   does not exist, leave `src` out: the figure draws a placeholder that shows the `alt` text.',
    '7. **Check it.** The figure is done when all of these hold:',
    '   - `npm test` passes. It fails on a figure name that does not exist and on `illustrative` data in',
    '     an entry without `placeholder: true`.',
    '   - `/in-practice/<id>/` renders with no error, and each figure reads well at desktop width and at',
    '     390 px. An unknown skill or territory id in a figure stops the page with a message naming it.',
    '   - Every number in the figure comes from the entry’s own data, and no "Screenshot to add"',
    '     placeholder is left, unless the entry still has `placeholder: true`.',
    '',
    'A full entry with a figure in every section: `src/content/fieldwork/_example-figures.mdx`.',
    '',
  );

  out.push('## Rules', '');
  out.push('### Colour', '', 'Colour carries meaning and nothing else.', '', '| Colour | Says |', '| --- | --- |', ...COLOURS.map((c) => `| ${c.name} | ${c.means} |`), '');
  out.push(
    'Pink marks the thing to look at, so one element per figure gets it: one `highlight`, one `pick`,',
    'one `signal`, one `tone: \'signal\'`.',
    '',
  );
  out.push(
    '### Evidence',
    '',
    'The entry\'s `method` already says how the whole piece is known: an interview is reported, a review',
    'is observed. A figure repeats it only when it adds something. Set `evidence` (and `source`) when:',
    '',
    '- the figure carries numbers or third-party facts: say who measured them and when;',
    '- it mixes kinds of knowing, or differs from the rest of the entry (an observed screenshot in an interview);',
    '- it is a guess or a plan (`assumed`) the reader could take as a result;',
    '- it is example data (`illustrative`, required).',
    '',
    'Leave it out on quotes, screenshots of the product being discussed, diagrams of a process someone',
    'described, scope lists and Skills Map figures. `Claims` sorts claims by evidence, so it always shows it.',
    '',
    '| `evidence` | Means |',
    '| --- | --- |',
    ...EVIDENCE_KINDS.map((e) => `| \`${e.id}\` | ${e.means} |`),
    '',
  );
  out.push(
    '### Words inside a figure',
    '',
    '- Plain and concrete, in the voice of the entry. Labels in sentence case with no full stop. A note is one line.',
    '- A title says what the figure shows ("New visitors, from landing page to a finished first lesson"). A caption says what to read from it.',
    '- Give counts where a figure asks for counts (`Funnel`, `ABResult`): it works out the rates and the intervals.',
    '- Every number carries its unit, through the `unit` prop where there is one.',
    '',
    '### MDX',
    '',
    '- A string prop takes quotes: `title="…"`. Everything else takes braces: `steps={[…]}`, `target={26}`, `flag={false}`.',
    '- A string that contains a double quote goes in braces: `text={\'She said "no"\'}`.',
    '- In prose, write `{` and `<` inside backticks or as `\\{` and `&lt;`. A comment is `{/* … */}`.',
    '',
    '### Motion',
    '',
    'Every figure plays once when it scrolls into view. Only figures whose reveal shows an order have a',
    'Replay button: `Sequence`, `Timeline`, `Journey`, `ScreenSteps`, `Rollout`, `Funnel` and `LineChart`.',
    '`replay={true}` adds the button to another figure, `replay={false}` removes it. `Flow` and `Loop` keep',
    'dots moving and have a Pause button instead; `motion={false}` makes them still.',
    'Nothing moves when the reader asks for reduced motion, and a figure reads the same without JavaScript.',
    '',
  );

  out.push('## Which figure for which section', '', 'The usual fits, most likely first. A starting point: a section with nothing to show gets no figure.', '');
  for (const k of PICKER) {
    out.push(`### ${k.label}`, '', '| Section | Figures |', '| --- | --- |');
    for (const s of k.sections) out.push(`| ${s.section} | ${s.figures.map((n) => link(byName.get(n)!)).join(' · ')} |`);
    out.push('');
  }

  out.push('## Figures by territory', '', 'For an entry that sits in one part of the Skills Map: the figures that serve each territory.', '', '| Territory | The question it answers | Figures |', '| --- | --- | --- |');
  const atlas = loadAtlas();
  const codes = nodeCodes(atlas);
  for (const t of atlas.territories) {
    const fits = FIGURES.filter((f) => f.group !== 'atlas' && f.territories.includes(t.id));
    out.push(`| ${codes.get(t.id)} ${t.name} | ${t.question} | ${fits.map((f) => link(f)).join(' · ')} |`);
  }
  out.push('', 'The Skills Map figures (`TerritoryMark`, `Territories`, `Skills`) work in every territory.', '');

  out.push('## Index', '');
  for (const g of GROUPS) {
    const figures = FIGURES.filter((f) => f.group === g.id);
    out.push(`### ${g.name}`, '', `${g.question} Reference: [${groupFile(g.id)}](${groupFile(g.id)}).`, '', '| Code | Figure | What it is |', '| --- | --- | --- |');
    for (const f of figures) out.push(`| ${f.code} | ${link(f)} | ${f.what} |`);
    out.push('');
  }

  out.push('## Props every figure accepts', '', 'They fill the frame: the title above, the caption and the source below.', '', ...FRAME_PROPS.map(prop), '');
  const frameless = FIGURES.filter((f) => f.frameless).map((f) => `\`${f.name}\``);
  out.push(`${frameless.join(' and ')} have no frame and take only their own props.`, '');
  out.push('`Figure` is the frame on its own. Wrap anything else in it (a table, a one-off SVG, an image) to give it', 'the same head and foot: `<Figure kind="Diagram" title="…" evidence="observed">…</Figure>`.', '');

  out.push(
    '## Add a figure to the library',
    '',
    '1. Write `src/components/figures/<Name>.astro` on top of `Figure.astro`. Inside `.fg-<name>`, class names start',
    '   with `x-`. Colours come from the five meanings above. Motion comes from `data-a` (plays once) and `data-l`',
    '   (loops) in `figures.css`; the resting style of every element is its final state.',
    '2. Add it to `index.ts` and to `catalog.ts`, with at least one example and the Skills Map skills it serves.',
    '3. Run `npm run figures:docs` and `npm test`. Look at it in `/figures/` at both preview widths and in the dark theme.',
    '',
  );
  return out.join('\n');
}

/** Every generated file, by its path under docs/. */
export function figureDocs(): Record<string, string> {
  const files: Record<string, string> = { 'figures.md': mainDoc() };
  for (const g of GROUPS) {
    if (FIGURES.some((f) => f.group === g.id)) files[groupFile(g.id)] = groupDoc(g.id);
  }
  return files;
}
